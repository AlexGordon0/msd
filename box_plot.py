data = [video_data, audio_data, multimodal_data]

plt.figure(figsize=(12, 12))  # better aspect ratio

box = plt.boxplot(
    data,
    # vert=False,
    labels=["video-only", "audio-only", "multimodal"],
    patch_artist=True,
    medianprops=dict(color="black", linewidth=2),
    boxprops=dict(linewidth=1.5),
    whiskerprops=dict(linewidth=1.5),
    capprops=dict(linewidth=1.5),
    flierprops=dict(marker="o", markersize=6, alpha=0.5),
)

# Add color to boxes
colors = ["#4C72B0", "#55A868", "#C44E52"]  # nice blue & green
for patch, color in zip(box["boxes"], colors):
    patch.set_facecolor(color)
    patch.set_alpha(0.6)

# Labels and title
plt.ylabel("DER (%)", fontsize=16)
# plt.title("DER Distribution: Video vs Audio", fontsize=14)

# Grid for readability
plt.grid(axis="y", linestyle="--", alpha=0.8)
plt.xticks(fontsize=16)

# Remove top/right spines for cleaner look
for spine in ["top", "right"]:
    plt.gca().spines[spine].set_visible(False)

plt.tight_layout()
